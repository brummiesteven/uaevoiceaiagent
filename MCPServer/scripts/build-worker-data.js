#!/usr/bin/env node
/**
 * Bake the data into a module the Worker can ship.
 *
 * data.dubai's firewall rejects datacenter IPs — verified against the JSON API,
 * not just the HTML pages — so a Cloudflare Worker can never fetch the
 * catalogue at runtime. It doesn't need to: the server already treats the
 * catalogue as a boot-time snapshot, so the Worker carries it in the bundle.
 *
 * Refreshing the data therefore means running the Node server once (from an IP
 * the firewall allows), then re-running this and redeploying.
 *
 *   npm start          # writes data/catalogue-snapshot.json
 *   npm run build:worker
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'worker', 'src', 'data.js');

// Only what the tools read. The full record carries ~100 fields, most of them
// empty contact boilerplate, and every byte is bundle size and parse time.
const KEEP = [
  'id', 'title', 'titleAr', 'description', 'themes', 'categories',
  'entity', 'entityKey', 'isStatistics', 'classification', 'views', 'downloads',
  'updateFrequency', 'apiEndpoint', 'source', 'url', 'ingestedAt',
];

const pick = (obj, keys) => Object.fromEntries(
  keys.map((k) => [k, obj[k]]).filter(([, v]) => v !== undefined && v !== null && v !== ''),
);

const snap = JSON.parse(await readFile(join(ROOT, 'data', 'catalogue-snapshot.json'), 'utf8'));
const indicators = JSON.parse(await readFile(join(ROOT, 'data', 'indicators.json'), 'utf8'));
const living = JSON.parse(await readFile(join(ROOT, 'data', 'living-in-dubai.json'), 'utf8'));

const catalogue = {
  savedAt: snap.savedAt,
  source: 'bundled',
  datasets: (snap.datasets || []).map((d) => pick(d, KEEP)),
  entities: snap.entities || [],
  themes: snap.themes || [],
  subthemes: snap.subthemes || [],
  publications: snap.publications || [],
};

const body = `// GENERATED by scripts/build-worker-data.js — do not edit by hand.
// Snapshot taken ${catalogue.savedAt}. Re-run \`npm run build:worker\` to refresh.
export const catalogue = ${JSON.stringify(catalogue)};
export const indicators = ${JSON.stringify(indicators)};
export const living = ${JSON.stringify(living)};
`;

await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, body, 'utf8');

const kb = n => `${(n / 1024).toFixed(0)} KB`;
console.log(`wrote ${OUT}`);
console.log(`  datasets   ${catalogue.datasets.length}`);
console.log(`  entities   ${catalogue.entities.length}`);
console.log(`  indicators ${indicators.indicators.length}`);
console.log(`  services   ${living.accessibility.length}`);
console.log(`  module     ${kb(Buffer.byteLength(body))}`);
